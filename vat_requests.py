AUTO = "[자동] "   # 시스템이 만든 파일 이름 앞에 붙이는 표시(같은 이름은 교체, 사용자가 올린 파일은 덮어쓰지 않음)


def step_status(step_id, names):
    """폴더 안 파일 이름들로 단계 상태를 판정. 반환 (아이콘, 문구)"""
    auto = [n for n in names if n.startswith(AUTO)]
    mine = [n for n in names if not n.startswith(AUTO)]
    memo = any(n.startswith(AUTO + "연회비") for n in names)
    if step_id == "bank":
        got = int(bool(auto)) + int(bool(mine))
        return ("✅", "완료") if got == 2 else (("🟡", "엑셀만 있음 — 원천징수영수증을 올려주세요") if auto else (("🟡", "영수증만 있음 — 거래내역 엑셀을 올려주세요") if mine else ("⬜", "아직")))
    if step_id == "card":
        files = [n for n in mine]
        if files and memo:
            return "✅", "완료"
        if files:
            return "🟡", "카드 내역은 있음 — 연회비 확인을 저장해주세요"
        return ("🟡", "연회비 확인만 있음 — 카드 내역을 올려주세요") if memo else ("⬜", "아직")
    if mine:
        return "✅", "완료"
    return ("🟡", "자동 생성 목록만 있음 — 파일을 올려주세요") if auto else ("⬜", "아직")
